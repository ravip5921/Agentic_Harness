
"""Release stage: prepare QA-approved implementations for review.

Trusted operations:
- Verify Developer and QA artifacts.
- Prepare an isolated release candidate.
- Persist release manifest and report.

The optional Release Agent generates advisory documentation.
If the agent fails, deterministic documentation is used.

This stage never modifies the original target repository.
"""

import logging
import os
import re
import tempfile

from collections.abc import Callable
from pathlib import Path

from harness.models import (
    ReleaseAssessment,
    ReleaseManifest,
    ReleaseResult,
    ReleaseStatus,
)
from harness.state import HarnessState

from harness.agents.release_agent import GroqReleaseAgent

from harness.tools.release_artifacts import (
    ReleaseArtifactError,
    load_release_artifacts,
)
from harness.tools.release_workspace import (
    ReleaseWorkspaceError,
    prepare_release_workspace,
)


logger = logging.getLogger(__name__)


class ReleaseStageError(Exception):
    """Raised when Release processing fails."""


def deterministic_release_assessment(
    manifest,
    qa_report,
    repository_path: str | None,
    agent_error: str | None = None,
) -> ReleaseAssessment:
    """Build factual release notes without using an LLM."""

    changes = [
        f"{record.operation.value.upper()}: {record.path}"
        for record in manifest.files
    ]

    passed_checks = [
        check.check_type.value
        for check in qa_report.checks
        if check.status.value == "passed"
    ]

    limitations = [
        "Candidate has not been merged, deployed, or "
        "applied to the original repository.",
        "Passing QA does not establish production readiness.",
    ]

    review_notes = [
        "Review the generated file changes before integration."
    ]

    if repository_path is None:
        review_notes.append(
            "This is a standalone release candidate."
        )
    else:
        review_notes.append(
            "This is a proposed integration candidate; "
            "the original repository remains unchanged."
        )

    if agent_error is not None:
        limitations.append(
            "Automated Release Agent documentation was unavailable; "
            "deterministic release notes were used."
        )
        review_notes.append(
            "Release Agent failure was recorded in the release report."
        )

    return ReleaseAssessment(
        summary=manifest.summary,
        changes=changes,
        testing_summary=(
            "QA report: PASS. Successful checks: "
            + (", ".join(passed_checks) or "none recorded")
            + ". Requirements assessment was accepted by "
            "the Release artifact validator."
        ),
        limitations=limitations,
        review_notes=review_notes,
    )


def render_release_report(
    assessment: ReleaseAssessment,
    *,
    agent_error: str | None = None,
) -> str:
    """Render release notes and agent status as Markdown."""

    def bullets(items):
        return "\n".join(f"- {item}" for item in items) or "- None"

    agent_status = (
        "Fallback: deterministic documentation"
        if agent_error is not None
        else "Generated by Release Agent"
    )

    return (
        "# Release Report\n\n"
        "## Summary\n\n"
        f"{assessment.summary}\n\n"
        "## Changes\n\n"
        f"{bullets(assessment.changes)}\n\n"
        "## Testing\n\n"
        f"{assessment.testing_summary}\n\n"
        "## Limitations\n\n"
        f"{bullets(assessment.limitations)}\n\n"
        "## Review Notes\n\n"
        f"{bullets(assessment.review_notes)}\n\n"
        "## Release Agent Status\n\n"
        f"{agent_status}\n\n"
        "## Release Status\n\n"
        "STAGED — candidate prepared for review. "
        "No merge or deployment was performed.\n"
    )


def write_text_atomic(path: Path, content: str) -> None:
    """Write an artifact through a temporary file."""

    path.parent.mkdir(parents=True, exist_ok=True)

    temporary = None

    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=path.parent,
            prefix=".release-",
            delete=False,
        ) as output:
            temporary = Path(output.name)
            output.write(content)

        os.replace(temporary, path)
        temporary = None

    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def make_release_stage(
    artifact_loader: Callable = load_release_artifacts,
    workspace_preparer: Callable = prepare_release_workspace,
    release_generator: Callable | None = None,
    runs_dir: Path = Path("runs"),
):
    """Create a LangGraph-compatible Release stage."""

    def release(state: HarnessState) -> dict:
        task = state.get("task")

        if task is None:
            return {
                "release_result": ReleaseResult(
                    status=ReleaseStatus.BLOCKED,
                    summary="Release requires a TaskRequest.",
                    errors=["Task is missing from state."],
                )
            }

        revision = state.get("revision_count", 0)

        if (
            isinstance(revision, bool)
            or not isinstance(revision, int)
            or revision < 0
            or revision > task.max_dev_revisions
        ):
            return {
                "release_result": ReleaseResult(
                    status=ReleaseStatus.BLOCKED,
                    summary="Invalid development revision counter.",
                )
            }

        if not re.fullmatch(r"[a-f0-9]{32}", task.run_id):
            return {
                "release_result": ReleaseResult(
                    status=ReleaseStatus.BLOCKED,
                    summary="Invalid run identifier.",
                )
            }

        runs_root = Path(runs_dir).resolve()

        release_dir = (
            runs_root
            / task.run_id
            / "release"
            / f"attempt-{revision}"
        )

        candidate_dir = release_dir / "candidate"
        manifest_path = release_dir / "release_manifest.json"
        report_path = release_dir / "release_report.md"
        assessment_path = release_dir / "release_assessment.json"

        # Avoid overwriting or mixing previous Release attempts.
        if release_dir.exists() or release_dir.is_symlink():
            return {
                "release_result": ReleaseResult(
                    status=ReleaseStatus.BLOCKED,
                    summary="Release attempt already exists.",
                    errors=[str(release_dir)],
                )
            }

        # Gate 1: QA authorization and artifact integrity.
        try:
            artifacts = artifact_loader(
                state,
                runs_dir=runs_root,
            )

        except ReleaseArtifactError as exc:
            return {
                "release_result": ReleaseResult(
                    status=ReleaseStatus.BLOCKED,
                    summary="Release prerequisites were not satisfied.",
                    errors=[str(exc)],
                )
            }

        # Gate 2: Prepare the isolated candidate.
        try:
            candidate = workspace_preparer(
                artifacts=artifacts,
                release_dir=candidate_dir,
                repository_path=task.repository_path,
            )

        except (ReleaseWorkspaceError, OSError, ValueError) as exc:
            return {
                "release_result": ReleaseResult(
                    status=ReleaseStatus.BLOCKED,
                    summary="Release candidate preparation failed.",
                    errors=[str(exc)],
                )
            }

        # Advisory step: Release Agent documentation.
        # This must not affect artifact validation or staging approval.
        agent_error = None

        if release_generator is not None:
            try:
                assessment = release_generator(
                    task,
                    artifacts.manifest,
                    artifacts.qa_report,
                )

                if not isinstance(assessment, ReleaseAssessment):
                    raise ReleaseStageError(
                        "Release Agent returned an invalid assessment."
                    )

            except Exception as exc:
                logger.warning(
                    "Release Agent unavailable for run %s, "
                    "attempt %d; using deterministic notes: %s",
                    task.run_id,
                    revision,
                    type(exc).__name__,
                )

                agent_error = type(exc).__name__

                assessment = deterministic_release_assessment(
                    artifacts.manifest,
                    artifacts.qa_report,
                    task.repository_path,
                    agent_error=agent_error,
                )

        else:
            agent_error = "AgentNotConfigured"

            assessment = deterministic_release_assessment(
                artifacts.manifest,
                artifacts.qa_report,
                task.repository_path,
                agent_error=agent_error,
            )

        # Gate 3: Persist factual release metadata and documentation.
        try:
            release_manifest = ReleaseManifest(
                run_id=task.run_id,
                revision_count=revision,
                summary=artifacts.manifest.summary,
                files=artifacts.manifest.files,
                source_manifest_path=str(artifacts.manifest_path),
                qa_report_path=str(artifacts.qa_report_path),
                repository_path=task.repository_path,
                release_directory=str(candidate),
            )

            write_text_atomic(
                manifest_path,
                release_manifest.model_dump_json(indent=2),
            )

            write_text_atomic(
                assessment_path,
                assessment.model_dump_json(indent=2),
            )

            write_text_atomic(
                report_path,
                render_release_report(
                    assessment,
                    agent_error=agent_error,
                ),
            )

        except (OSError, ValueError) as exc:
            return {
                "release_result": ReleaseResult(
                    status=ReleaseStatus.FAILED,
                    summary="Release documentation could not be saved.",
                    errors=[str(exc)],
                )
            }

        return {
            "release_result": ReleaseResult(
                status=ReleaseStatus.STAGED,
                summary=(
                    "QA-approved implementation staged for review."
                    if agent_error is None
                    else (
                        "QA-approved implementation staged with "
                        "deterministic release documentation."
                    )
                ),
                change_ref=str(candidate),
            )
        }

    return release


def release(state: HarnessState) -> dict:
    """Default Release stage with optional Groq documentation."""

    # Initialize Groq inside the advisory callback so even
    # initialization or configuration failures use the fallback.
    def generate_notes(task, manifest, qa_report):
        agent = GroqReleaseAgent()
        return agent.generate(task, manifest, qa_report)

    node = make_release_stage(
        release_generator=generate_notes,
    )

    return node(state)
